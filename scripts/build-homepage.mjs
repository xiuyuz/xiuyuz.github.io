import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { renderPage } from "../assets/site/template.js";
import { data } from "../assets/site/data.js";

const target = new URL("../index.html", import.meta.url);
const siteUrl = "https://xiuyuz.github.io/";
const description =
  "XiuYu Zhang is a Computer Science Ph.D. student at the National University of Singapore, researching reasoning and representation, AI safety and alignment, and multimodal intelligence.";
const structuredData = {
  "@context": "https://schema.org",
  "@type": "Person",
  name: data.name,
  url: siteUrl,
  jobTitle: "Computer Science Ph.D. student",
  affiliation: { "@type": "CollegeOrUniversity", name: data.institution },
  sameAs: [data.scholarUrl, data.githubUrl],
};
const page = `<!doctype html>
<!-- Generated by npm run build:home. Edit assets/site/data.js and template.js. -->
<html lang="en" class="no-js">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>XiuYu Zhang</title>
  <meta name="description" content="${description}">
  <meta name="author" content="XiuYu Zhang">
  <link rel="canonical" href="${siteUrl}">
  <meta property="og:type" content="profile">
  <meta property="og:title" content="XiuYu Zhang">
  <meta property="og:description" content="${description}">
  <meta property="og:url" content="${siteUrl}">
  <meta property="og:image" content="${siteUrl}assets/site/banner/artwork.png">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="theme-color" content="#18222f">
  <link rel="icon" href="/assets/img/favicon.svg" type="image/svg+xml">
  <link rel="icon" href="/assets/img/favicon-32.png" type="image/png" sizes="32x32">
  <link rel="apple-touch-icon" href="/assets/img/apple-touch-icon.png" sizes="180x180">
  <script src="/assets/site/appearance-init.js"></script>
  <style>html[data-theme="dark"],html[data-theme="dark"] body{background:#10151e}</style>
  <link rel="stylesheet" href="/assets/site/base.css">
  <link rel="stylesheet" href="/assets/site/concepts/homepage.css">
  <link rel="stylesheet" href="/assets/site/banner/banner.css">
  <link rel="stylesheet" href="/assets/site/banner/particle-refinements.css">
  <link rel="stylesheet" href="/assets/site/concepts/contour-finish.css">
  <link rel="stylesheet" href="/assets/site/progressive.css">
  <script type="application/ld+json">${JSON.stringify(structuredData).replaceAll("<", "\\u003c")}</script>
  <script type="module" src="/assets/site/main.js"></script>
</head>
<body>
  <main id="site-root">${renderPage(data)}</main>
  <noscript><p class="ct-noscript-note">Enable JavaScript to reveal and copy my email address.</p></noscript>
</body>
</html>`;
const options = await resolveConfig(fileURLToPath(target));
const output = await format(page, { ...options, filepath: fileURLToPath(target) });
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== output) {
    console.error("index.html is out of date. Run npm run build:home.");
    process.exitCode = 1;
  } else console.log("The generated homepage is up to date.");
} else {
  await writeFile(target, output);
  console.log("Built index.html with the complete biography and selected research.");
}
